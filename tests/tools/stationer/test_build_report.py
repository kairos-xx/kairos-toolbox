@final
class Constants:
    """Group module-level constants.

    Attributes:
        commit: Grouped module constant.

    """

    commit: Final[str] = "abc1234"


def git_commit(*, arguments: tuple[str, ...]) -> str | None:
    """Answer ``git`` with a fixed commit, and stay silent otherwise.

    Args:
        arguments: Command being faked.

    Returns:
        The commit for ``git`` calls, else nothing.

    """
    return f"{Constants.commit}\n" if arguments[0] == "git" else None


def _configuration(*, root: Path, architecture: str) -> BuildConfiguration:
    """Create a Linux-only configuration for one architecture.

    Args:
        root: Project root.
        architecture: Docker architecture, e.g. ``arm64``.

    Returns:
        The configuration.

    """
    root.mkdir(parents=True, exist_ok=True)
    (root / "app.py").write_text(data="print('ok')\n", encoding="utf-8")
    return BuildConfiguration(
        project=ProjectConfig(
            root=root,
            name="demo",
            version="1.2.3",
            entrypoint=root / "app.py",
            identifier="dev.example.demo",
            console=True,
            pyinstaller_args=(),
            pip_args=(),
        ),
        linux=LinuxConfig(
            docker_platform=f"linux/{architecture}",
            image="img",
            maintainer="M",
            description="D",
        ),
        macos=MacOSConfig(python="python3", signing_identity=None),
        windows=None,
    )


def _build(*, tmp_path: Path, architecture: str) -> Path:
    """Run one Linux build into ``tmp_path / "build"``.

    Args:
        tmp_path: Pytest temporary directory.
        architecture: Docker architecture.

    Returns:
        The output directory.

    """
    output: Path = tmp_path / "build"
    platforms: tuple[PlatformName, ...] = ("linux",)
    _ = ReleaseBuilder(
        open_host=Hosts(handler=git_commit),
        containers=Opener(),
    ).build(
        configuration=_configuration(
            root=tmp_path / "src",
            architecture=architecture,
        ),
        output=output,
        platforms=platforms,
    )
    return output


def test_build_md_describes_the_build(tmp_path: Path) -> None:
    """The report names the project, commit, artifacts and digests.

    Args:
        tmp_path: Pytest temporary directory.

    """
    output: Path = _build(tmp_path=tmp_path, architecture="arm64")
    text: str = (output / "BUILD.md").read_text(encoding="utf-8")
    executable: Path = (
        output
        / "linux"
        / "arm64"
        / "glibc"
        / "demo"
        / "pyinstaller"
        / "demo-1.2.3-linux-arm64"
    )
    digest: str = sha256(data=executable.read_bytes()).hexdigest()
    for needle in (
        "# Build",
        "Generated by `tools.stationer`",
        "demo 1.2.3",
        "abc1234",
        "| linux | arm64 |",
        "linux/arm64/glibc/demo/pyinstaller/demo-1.2.3-linux-arm64",
        "linux/arm64/glibc/demo/installer/demo_1.2.3_arm64.deb",
        digest,
        "--platform linux",
    ):
        check(condition=needle in text, reason=f"{needle!r} not in:\n{text}")
    check(
        condition=str(object=tmp_path) not in text,
        reason="the report must not leak absolute paths",
    )


def test_runs_merge_instead_of_overwriting(tmp_path: Path) -> None:
    """A later partial build keeps the earlier platforms' entries.

    Args:
        tmp_path: Pytest temporary directory.

    """
    _ = _build(tmp_path=tmp_path, architecture="arm64")
    output: Path = _build(tmp_path=tmp_path, architecture="amd64")
    entries: list[dict[str, object]] = loads(
        s=(output / "artifacts.json").read_text(encoding="utf-8"),
    )
    expect(
        actual=sorted(str(object=e["architecture"]) for e in entries),
        expected=["amd64", "arm64"],
    )
    text: str = (output / "BUILD.md").read_text(encoding="utf-8")
    check(condition="| linux | arm64 |" in text, reason=text)
    check(condition="| linux | amd64 |" in text, reason=text)


def test_rebuilding_a_platform_replaces_its_entry(tmp_path: Path) -> None:
    """The same platform and architecture appears once.

    Args:
        tmp_path: Pytest temporary directory.

    """
    _ = _build(tmp_path=tmp_path, architecture="arm64")
    output: Path = _build(tmp_path=tmp_path, architecture="arm64")
    entries: list[dict[str, object]] = loads(
        s=(output / "artifacts.json").read_text(encoding="utf-8"),
    )
    expect(actual=len(entries), expected=1)
    check(condition="built_at" in entries[0], reason=str(object=entries[0]))


def test_entries_whose_files_vanished_are_dropped(tmp_path: Path) -> None:
    """The report only lists artifacts that still exist.

    Args:
        tmp_path: Pytest temporary directory.

    """
    first: Path = _build(tmp_path=tmp_path, architecture="arm64")
    (
        first
        / "linux"
        / "arm64"
        / "glibc"
        / "demo"
        / "pyinstaller"
        / "demo-1.2.3-linux-arm64"
    ).unlink()
    output: Path = _build(tmp_path=tmp_path, architecture="amd64")
    entries: list[dict[str, object]] = loads(
        s=(output / "artifacts.json").read_text(encoding="utf-8"),
    )
    expect(actual=[e["architecture"] for e in entries], expected=["amd64"])


def test_pyz_archives_are_listed(tmp_path: Path) -> None:
    """``.pyz`` files in the output directory appear in an archives table.

    Args:
        tmp_path: Pytest temporary directory.

    """
    output: Path = _build(tmp_path=tmp_path, architecture="arm64")
    archive: Path = output / "demo-1.2.3-macos-arm64.pyz"
    archive.write_bytes(data=b"zip")
    _ = BuildReport.write(
        output=output,
        source=BuildSource(name="demo", version="1.2.3"),
        open_host=Hosts(handler=git_commit),
    )
    text: str = (output / "BUILD.md").read_text(encoding="utf-8")
    check(condition="## Archives" in text, reason=text)
    check(condition=archive.name in text, reason=text)
    check(condition=sha256(data=b"zip").hexdigest() in text, reason=text)


def test_report_without_builds_still_renders(tmp_path: Path) -> None:
    """An empty output directory yields an honest, valid report.

    Args:
        tmp_path: Pytest temporary directory.

    """
    output: Path = tmp_path / "build"
    output.mkdir()
    path: Path = BuildReport.write(
        output=output,
        source=BuildSource(name="demo", version="1.2.3"),
        open_host=Hosts(handler=git_commit),
    )
    text: str = path.read_text(encoding="utf-8")
    check(condition="No builds yet" in text, reason=text)


def test_render_is_deterministic() -> None:
    """The same inputs always produce the same text."""
    source: BuildSource = BuildSource(name="demo", version="1.2.3")
    provenance: Provenance = Provenance(
        commit="abc1234",
        host="Darwin 25 arm64 · Python 3.13",
        generated_at="2026-10-23T12:00:00Z",
    )
    first: str = BuildReport.render(
        source=source,
        provenance=provenance,
        entries=[],
        archives=[],
    )
    expect(
        actual=first,
        expected=BuildReport.render(
            source=source,
            provenance=provenance,
            entries=[],
            archives=[],
        ),
    )
    check(condition="No builds yet." in first, reason=first)


def test_cli_defaults_the_output_to_build(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Without ``--output`` the executables go to ``./build``.

    Args:
        tmp_path: Pytest temporary directory.
        monkeypatch: Pytest monkeypatch fixture.

    """
    root: Path = tmp_path / "proj"
    root.mkdir()
    (root / "app.py").write_text(data="print()\n", encoding="utf-8")
    manifest: Path = tmp_path / "m.toml"
    manifest.write_text(
        data=(
            '[project]\nname = "demo"\nversion = "1.2.3"\nentrypoint = '
            '"app.py"\n'
        ),
        encoding="utf-8",
    )
    seen: list[Path] = []

    def fake_build(
        self: ReleaseBuilder,
        *,
        output: Path,
        **ignored: BuildConfiguration
        | tuple[PlatformName, ...]
        | str
        | tuple[str, ...],
    ) -> tuple[()]:
        """Record the output directory used by the build.

        Args:
            self: The ``ReleaseBuilder`` instance (unused).
            output: Directory receiving artifacts.
            **ignored: Other build arguments (unused).

        Returns:
            No build results.

        """
        _ = (self, ignored)
        seen.append(output)
        return ()

    monkeypatch.chdir(path=tmp_path)
    monkeypatch.setattr(target=ReleaseBuilder, name="build", value=fake_build)
    expect(
        actual=Cli.main(
            arguments=(
                "--project",
                str(object=root),
                "--manifest",
                str(object=manifest),
                "--platform",
                "linux",
            ),
        ),
        expected=0,
    )
    expect(actual=seen, expected=[(tmp_path / "build").resolve()])
